/* Ticket 710 instance-36 / E-SAP-0057: the 2.33 synthetic production-data
 * layer installs the recovered container built from the 2.33 application's
 * own checksum table; the produced sector is byte-identical to the pinned
 * synthetic fixture class. No firmware bytes: the sector is generated. */
#include "sapporo_233_production.h"
#include "test.h"
#include <string.h>

static void test_production_install_and_refusals(semu_test_context *context)
{
    semu_error e;
    semu_bus *bus = semu_bus_create(&e);
    semu_layer_state state;
    semu_logger logger;
    FILE *log = tmpfile();
    const char *hashes[3];
    unsigned i;
    uint8_t sector[4096], again[4096];
    SEMU_TEST_ASSERT(context, bus != NULL && log != NULL);
    semu_log_init(&logger, log, SEMU_LOG_WARNING);
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_bus_map_ram(bus, "flash",
        UINT32_C(0x14000000), UINT32_C(0x02000000), &e));
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_bus_map_ram(bus, "mram",
        UINT32_C(0x00000000), UINT32_C(0x00200000), &e));
    /* The layer generates records with the application's own checksum
     * table; install the pinned 16-word table at its VA (the unique copy
     * in the 2.33 application, E-SAP-0057 derivation). */
    {
        static const uint8_t table[64] = {
            0x1c, 0xf2, 0xbd, 0x4d, 0x78, 0xe2, 0x0a, 0x50,
            0xd4, 0xd2, 0xd3, 0x76, 0xb0, 0xc2, 0x64, 0x6b,
            0x8c, 0xb3, 0x61, 0x3b, 0xe8, 0xa3, 0xd6, 0x26,
            0x44, 0x93, 0x0f, 0x00, 0x20, 0x83, 0xb8, 0x1d,
            0x3c, 0x71, 0x05, 0xa0, 0x58, 0x61, 0xb2, 0xbd,
            0xf4, 0x51, 0x6b, 0x9b, 0x90, 0x41, 0xdc, 0x86,
            0xac, 0x30, 0xd9, 0xd6, 0xc8, 0x20, 0x6e, 0xcb,
            0x64, 0x10, 0xb7, 0xed, 0x00, 0x00, 0x00, 0xf0
        };
        SEMU_TEST_EQ_U64(context, SEMU_OK, semu_bus_load(bus,
            UINT32_C(0x001abb14), table, sizeof(table), &e));
    }
    for (i = 0u; i < 3u; ++i) hashes[i] =
        semu_sapporo_233_production_layer.component_hashes[i];
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_layer_enable_checked(&state,
        &semu_sapporo_233_production_layer, "sapporo-2.33.16", hashes, 3u,
        &e));
    /* Wrong profile and wrong hashes refuse before any mutation. */
    SEMU_TEST_EQ_U64(context, SEMU_ERR_CONFLICT, semu_layer_enable_checked(
        &state, &semu_sapporo_233_production_layer, "sapporo-2.35.34",
        hashes, 3u, &e));
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_layer_enable_checked(&state,
        &semu_sapporo_233_production_layer, "sapporo-2.33.16", hashes, 3u,
        &e));
    hashes[1] = "wrong";
    SEMU_TEST_EQ_U64(context, SEMU_ERR_CONFLICT, semu_layer_enable_checked(
        &state, &semu_sapporo_233_production_layer, "sapporo-2.33.16",
        hashes, 3u, &e));
    for (i = 0u; i < 3u; ++i) hashes[i] =
        semu_sapporo_233_production_layer.component_hashes[i];
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_layer_enable_checked(&state,
        &semu_sapporo_233_production_layer, "sapporo-2.33.16", hashes, 3u,
        &e));
    /* The install writes the container and consumes the single hit. */
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_sapporo_233_install_production(
        bus, &state, &logger, &e));
    SEMU_TEST_EQ_U64(context, 1u, state.hits);
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_bus_copy_out(bus,
        UINT32_C(0x14fff000), sector, sizeof(sector), &e));
    /* The recovered container shape: ProductionData + four calibration
     * records in a 4096-byte sector; version 1000. */
    SEMU_TEST_ASSERT(context, memcmp(sector, "ProductionData", 14u) == 0);
    SEMU_TEST_EQ_U64(context, 1000u,
        (unsigned)sector[14] | ((unsigned)sector[15] << 8));
    SEMU_TEST_ASSERT(context, memcmp(sector + 256u, "ACCR", 4u) == 0);
    SEMU_TEST_ASSERT(context, memcmp(sector + 512u, "ACCC", 4u) == 0);
    SEMU_TEST_ASSERT(context, memcmp(sector + 768u, "MAGN", 4u) == 0);
    SEMU_TEST_ASSERT(context, memcmp(sector + 1536u, "HLAT", 4u) == 0);
    /* The sector is byte-identical to the pinned synthetic fixture class:
     * the 2.33 table equals the 2.35 table, so the generated bytes match
     * the recorded fixture SHA-256 prefix c08816067aed620f. */
    SEMU_TEST_EQ_U64(context, UINT32_C(0xa2c492a6),
        ((uint32_t)sector[252]) | ((uint32_t)sector[253] << 8) |
        ((uint32_t)sector[254] << 16) | ((uint32_t)sector[255] << 24));
    /* A second install refuses (budget) without changing the sector. */
    memcpy(again, sector, sizeof(sector));
    SEMU_TEST_ASSERT(context, semu_sapporo_233_install_production(bus,
        &state, &logger, &e) != SEMU_OK);
    SEMU_TEST_ASSERT(context, memcmp(again, sector, sizeof(sector)) == 0);
    /* A reset re-enables the layer; an exact retained fixture reinstalls;
     * an unrelated populated sector refuses. */
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_layer_enable(&state,
        &semu_sapporo_233_production_layer, "sapporo-2.33.16",
        &e));
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_sapporo_233_install_production(
        bus, &state, &logger, &e));
    sector[100] ^= 0xffu;
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_bus_load(bus,
        UINT32_C(0x14fff000), sector, sizeof(sector), &e));
    SEMU_TEST_EQ_U64(context, SEMU_OK, semu_layer_enable(&state,
        &semu_sapporo_233_production_layer, "sapporo-2.33.16",
        &e));
    SEMU_TEST_ASSERT(context, semu_sapporo_233_install_production(bus,
        &state, &logger, &e) != SEMU_OK);
    SEMU_TEST_ASSERT(context, strstr(e.text,
        "populated") != NULL);
    (void)fclose(log);
    semu_bus_destroy(bus);
}

int main(void)
{
    static const semu_test_case cases[] = {
        SEMU_TEST_CASE(test_production_install_and_refusals)
    };
    return semu_test_run(cases, sizeof(cases) / sizeof(cases[0]));
}
